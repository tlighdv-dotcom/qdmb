create policy "admin read profile objects" on storage.objects for select to authenticated using (bucket_id='member-profiles' and (((select auth.jwt()) -> 'app_metadata' ->> 'role')='admin'));
drop policy if exists "admin upload profile objects" on storage.objects;
create policy "admin upload profile objects" on storage.objects for insert to authenticated with check (bucket_id='member-profiles' and (((select auth.jwt()) -> 'app_metadata' ->> 'role')='admin'));
drop policy if exists "admin update profile objects" on storage.objects;
create policy "admin update profile objects" on storage.objects for update to authenticated using (bucket_id='member-profiles' and (((select auth.jwt()) -> 'app_metadata' ->> 'role')='admin')) with check (bucket_id='member-profiles' and (((select auth.jwt()) -> 'app_metadata' ->> 'role')='admin'));
drop policy if exists "admin delete profile objects" on storage.objects;
create policy "admin delete profile objects" on storage.objects for delete to authenticated using (bucket_id='member-profiles' and (((select auth.jwt()) -> 'app_metadata' ->> 'role')='admin'));

do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='members') then
    execute 'alter publication supabase_realtime add table public.members';
  end if;
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='member_status_logs') then
    execute 'alter publication supabase_realtime add table public.member_status_logs';
  end if;
end $$;
